// Dateifunktionen des Struktogramms (fileOpen … fileWriteLine, Plan 6.2) als kleine Hilfsschicht je Zielsprache.
// Verhalten wie im Interpreter (executor.js, fileBuiltin): Nummer einer Datei = Position in der Liste + 1, Fehlercodes
// -2 (nicht gefunden), -3 (kein Zugriff), -1 (anderer Fehler); zum Lesen wird die ganze Datei geladen, Schreiben hängt
// an. Gelesen wird wortweise (fileReadInt, fileReadDouble, fileRead), zeichenweise (fileReadChar, Zeichen = Unicode-
// Zeichen, \r\n = \n) oder zeilenweise (fileReadLine, ohne \r).
//
// Namen der Hilfsfunktionen (in allen Sprachen gleich): file_open, file_create, file_append, file_close, file_eof,
// file_read_int, file_read_double, file_read_char, file_read_line, file_read_str (fileRead in eine Text-Variable),
// file_read (fileRead ohne festen Typ – nur Python und JavaScript), file_write (Text anhängen).
'use strict';
const { t: tr } = require('../i18n');

/** Fehlertext mit Platzhalter {0}: [vorher, nachher] */
function parts(key) { return tr(key, '\u0000').split('\u0000'); }
const q = (s) => JSON.stringify(s);

/** Zahl wie im Interpreter (ohne Exponent- und Sonderformen wie inf, 0x…) */
const NUM_RE = '^[+-]?(\\d+(\\.\\d*)?|\\.\\d+)([eE][+-]?\\d+)?$';

function python() {
  const [r1, r2] = parts('exec.fileNotOpenRead'), [w1, w2] = parts('exec.fileNotOpenWrite');
  const [i1, i2] = parts('exec.notInt'), [n1, n2] = parts('exec.notNumber');
  return [
    '# ' + tr('gen.files'),
    '_files = []',
    '',
    'def _file_new(p, mode, text):',
    '    try:',
    '        if mode == "r":',
    '            with open(p, encoding="utf-8", newline="") as f:',
    '                text = f.read()',
    '        else:',
    '            open(p, mode, encoding="utf-8").close()',
    '    except FileNotFoundError:',
    '        return -2',
    '    except PermissionError:',
    '        return -3',
    '    except OSError:',
    '        return -1',
    '    _files.append({"r": mode == "r", "text": text, "pos": 0, "path": p})',
    '    return len(_files)',
    '',
    'def file_open(p): return _file_new(p, "r", "")',
    'def file_create(p): return _file_new(p, "w", "")',
    'def file_append(p): return _file_new(p, "a", "")',
    '',
    'def file_close(h):',
    '    if 1 <= h <= len(_files):',
    '        _files[h - 1] = None',
    '',
    'def _file(h, r):',
    '    f = _files[h - 1] if 1 <= h <= len(_files) else None',
    '    if f is None or f["r"] != r:',
    `        raise RuntimeError((${q(r1)} + str(h) + ${q(r2)}) if r else (${q(w1)} + str(h) + ${q(w2)}))`,
    '    return f',
    '',
    'def file_eof(h):',
    '    f = _file(h, True)',
    '    return f["text"][f["pos"]:].strip() == ""',
    '',
    'def _file_skip(f, err):',
    '    t, i = f["text"], f["pos"]',
    '    while i < len(t) and t[i].isspace():',
    '        i += 1',
    '    if i >= len(t):',
    `        raise RuntimeError(${q(tr('exec.eofData'))})`,
    '    return t, i',
    '',
    'def _file_token(f):',
    '    t, i = _file_skip(f, True)',
    '    j = i',
    '    while j < len(t) and not t[j].isspace():',
    '        j += 1',
    '    f["pos"] = j',
    '    return t[i:j]',
    '',
    'def file_read_int(h):',
    '    import re',
    '    s = _file_token(_file(h, True))',
    '    if not re.fullmatch(r"[+-]?[0-9]+", s):',
    `        raise ValueError(${q(i1)} + s + ${q(i2)})`,
    '    return int(s)',
    '',
    'def file_read_double(h):',
    '    import re',
    '    s = _file_token(_file(h, True))',
    `    if not re.fullmatch(r"${NUM_RE.slice(1, -1).replace(/\\d/g, '[0-9]')}", s):`,
    `        raise ValueError(${q(n1)} + s + ${q(n2)})`,
    '    return float(s)',
    '',
    'def file_read_char(h):',
    '    f = _file(h, True)',
    '    t, i = f["text"], f["pos"]',
    '    if i >= len(t):',
    `        raise RuntimeError(${q(tr('exec.eofChar'))})`,
    '    if t.startswith("\\r\\n", i):',
    '        f["pos"] = i + 2',
    '        return "\\n"',
    '    f["pos"] = i + 1',
    '    return t[i]',
    '',
    'def file_read_line(h):',
    '    f = _file(h, True)',
    '    t, i = f["text"], f["pos"]',
    '    if i >= len(t):',
    `        raise RuntimeError(${q(tr('exec.eofLine'))})`,
    '    j = t.find("\\n", i)',
    '    if j < 0:',
    '        j = len(t)',
    '    f["pos"] = j + 1',
    '    s = t[i:j]',
    '    return s[:-1] if s.endswith("\\r") else s',
    '',
    '# fileRead: "Text", \'Text\' und {Liste} am Stück, sonst ein Wort',
    'def _file_raw(h):',
    '    f = _file(h, True)',
    '    t, i = _file_skip(f, True)',
    '    c = t[i]',
    '    if c in "\\"\'{":',
    '        e = t.find("}" if c == "{" else c, i + 1)',
    '        if e < 0:',
    '            e = len(t)',
    '        f["pos"] = e + 1',
    '        return c, t[i + 1:e], t[i:e + 1]',
    '    f["pos"] = i',
    '    w = _file_token(f)',
    '    return "", w, w',
    '',
    'def file_read_str(h):',
    '    c, inner, raw = _file_raw(h)',
    '    return raw if c == "{" else inner',
    '',
    'def _file_value(s):',
    '    import re',
    '    s = s.strip()',
    '    if re.fullmatch(r"[+-]?[0-9]+", s):',
    '        return int(s)',
    `    if re.fullmatch(r"${NUM_RE.slice(1, -1).replace(/\\d/g, '[0-9]')}", s):`,
    '        return float(s)',
    '    if s.lower() in ("true", "false"):',
    '        return s.lower() == "true"',
    '    return s',
    '',
    'def file_read(h):',
    '    import re',
    '    c, inner, raw = _file_raw(h)',
    '    if c == "{":',
    '        if not inner.strip():',
    '            return []',
    '        return [x.strip()[1:-1] if re.fullmatch(r"([\\"\']).*\\1", x.strip()) else _file_value(x) for x in re.split(r"\\s*,\\s*", inner)]',
    '    return inner if c else _file_value(inner)',
    '',
    'def file_write(h, s):',
    '    with open(_file(h, False)["path"], "a", encoding="utf-8", newline="") as f:',
    '        f.write(s)',
    '',
    'def file_writeln(h, s):',
    '    file_write(h, s + "\\n")',
  ];
}

function javascript() {
  const [r1, r2] = parts('exec.fileNotOpenRead'), [w1, w2] = parts('exec.fileNotOpenWrite');
  const [i1, i2] = parts('exec.notInt'), [n1, n2] = parts('exec.notNumber');
  return [
    '// ' + tr('gen.files'),
    'const _fs = require("fs");',
    'const _files = [];',
    'const _fileErr = (e) => (e.code === "ENOENT" ? -2 : e.code === "EACCES" || e.code === "EPERM" ? -3 : -1);',
    'function _fileNew(p, mode) {',
    '    try {',
    '        const text = mode === "r" ? _fs.readFileSync(String(p), "utf8") : "";',
    '        if (mode === "w") _fs.writeFileSync(String(p), ""); else if (mode === "a") _fs.appendFileSync(String(p), "");',
    '        _files.push({ r: mode === "r", text, pos: 0, path: String(p) });',
    '        return _files.length;',
    '    } catch (e) { return _fileErr(e); }',
    '}',
    'const file_open = (p) => _fileNew(p, "r");',
    'const file_create = (p) => _fileNew(p, "w");',
    'const file_append = (p) => _fileNew(p, "a");',
    'const file_close = (h) => { if (_files[h - 1]) _files[h - 1] = null; };',
    'function _file(h, r) {',
    '    const f = _files[h - 1];',
    `    if (!f || f.r !== r) throw new Error(r ? ${q(r1)} + h + ${q(r2)} : ${q(w1)} + h + ${q(w2)});`,
    '    return f;',
    '}',
    'const file_eof = (h) => { const f = _file(h, true); return !/\\S/.test(f.text.slice(f.pos)); };',
    'function _fileToken(f) {',
    '    const m = /\\S+/.exec(f.text.slice(f.pos));',
    `    if (!m) throw new Error(${q(tr('exec.eofData'))});`,
    '    f.pos += m.index + m[0].length;',
    '    return m[0];',
    '}',
    'function file_read_int(h) {',
    '    const s = _fileToken(_file(h, true));',
    `    if (!/^[+-]?\\d+$/.test(s)) throw new Error(${q(i1)} + s + ${q(i2)});`,
    '    return parseInt(s, 10);',
    '}',
    'function file_read_double(h) {',
    '    const s = _fileToken(_file(h, true));',
    `    if (!/${NUM_RE}/.test(s)) throw new Error(${q(n1)} + s + ${q(n2)});`,
    '    return parseFloat(s);',
    '}',
    'function file_read_char(h) {',
    '    const f = _file(h, true);',
    `    if (f.pos >= f.text.length) throw new Error(${q(tr('exec.eofChar'))});`,
    '    if (f.text.startsWith("\\r\\n", f.pos)) { f.pos += 2; return "\\n"; }',
    '    const c = String.fromCodePoint(f.text.codePointAt(f.pos));',
    '    f.pos += c.length;',
    '    return c;',
    '}',
    'function file_read_line(h) {',
    '    const f = _file(h, true);',
    `    if (f.pos >= f.text.length) throw new Error(${q(tr('exec.eofLine'))});`,
    '    const nl = f.text.indexOf("\\n", f.pos);',
    '    const end = nl < 0 ? f.text.length : nl;',
    '    const s = f.text.slice(f.pos, end).replace(/\\r$/, "");',
    '    f.pos = end + 1;',
    '    return s;',
    '}',
    '// fileRead: "Text", \'Text\' und {Liste} am Stück, sonst ein Wort',
    'function _fileRaw(h) {',
    '    const f = _file(h, true);',
    '    const ws = /^\\s*/.exec(f.text.slice(f.pos))[0].length;',
    '    const i = f.pos + ws, c = f.text[i];',
    `    if (c === undefined) throw new Error(${q(tr('exec.eofData'))});`,
    '    if (c === "\\"" || c === "\'" || c === "{") {',
    '        let e = f.text.indexOf(c === "{" ? "}" : c, i + 1);',
    '        if (e < 0) e = f.text.length;',
    '        f.pos = e + 1;',
    '        return [c, f.text.slice(i + 1, e), f.text.slice(i, e + 1)];',
    '    }',
    '    const w = _fileToken(f);',
    '    return ["", w, w];',
    '}',
    'function file_read_str(h) { const [c, inner, raw] = _fileRaw(h); return c === "{" ? raw : inner; }',
    'function _fileValue(x) {',
    '    const s = x.trim();',
    '    if (/^[+-]?\\d+$/.test(s)) return parseInt(s, 10);',
    `    if (/${NUM_RE}/.test(s)) return parseFloat(s);`,
    '    if (/^(true|false)$/i.test(s)) return s.toLowerCase() === "true";',
    '    return s;',
    '}',
    'function file_read(h) {',
    '    const [c, inner] = _fileRaw(h);',
    '    if (c === "{") return inner.trim() ? inner.split(/\\s*,\\s*/).map((x) => (/^(["\']).*\\1$/.test(x.trim()) ? x.trim().slice(1, -1) : _fileValue(x))) : [];',
    '    return c ? inner : _fileValue(inner);',
    '}',
    'const file_write = (h, s) => _fs.appendFileSync(_file(h, false).path, String(s), "utf8");',
    'const file_writeln = (h, s) => file_write(h, String(s) + "\\n");',
  ];
}

